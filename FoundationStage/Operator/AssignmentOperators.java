package FoundationStage.Operator;

public class AssignmentOperators {
    public static void main(String[] args) {
          int x = 10;
        
        x += 5;  // x = x + 5
        x -= 2;  // x = x - 2
        x *= 3;  // x = x * 3
        
        System.out.println("Final Value: " + x);
    }
}
