

public class NonPrimitiveDataTypes {
    public static void main(String[] args) {
         String city = "Udupi";             // String
        int[] marks = {85, 90, 95};        // Array
       
        System.out.println("City: " + city);
        System.out.println("Marks: " + marks[0] + ", " + marks[1] + ", " + marks[2]);
    }
}
